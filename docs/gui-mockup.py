# Generates the GUI mockups:
#   gui-mockup-map.svg    - left column showing the map panel (default)
#   gui-mockup-rooms.svg  - left column swapped to the room/timeline panel
# Run: python docs/gui-mockup.py, then render each SVG to PNG in a browser.
import io
import os

DOCS = os.path.dirname(os.path.abspath(__file__)) + os.sep

RED = '#c62828'
BLUE = '#1e5bd6'
TOP = 110          # y of 11PM
PX_HOUR = 115      # 15-minute slot = 28.75px
BOTTOM = TOP + PX_HOUR * 8

LEFT_X, LEFT_W = 16, 874        # left column: map panel or room/timeline panel
V_W = 412                       # viewer panels (about 66% of the earlier 625)
V1_X = LEFT_X + LEFT_W + 16
V2_X = V1_X + V_W + 10
TL_X, TL_W = 1750, 154          # timeline panel

# rooms: (id, map x, map y, map w, map h, badge IDs at 01:10, viewer colour)
ROOMS = [
    ('1111', 44, 120, 200, 110, ['#4553 Bob', '#2210'], RED),
    ('2222', 300, 120, 200, 110, ['#3302'], None),
    ('6666', 556, 120, 300, 110, ['#5120'], None),
    ('3333', 44, 280, 200, 130, ['no proximity', '??'], None),
    ('4444', 300, 280, 200, 130, [], None),
    ('7777', 556, 280, 300, 130, [], None),
    ('5555', 44, 460, 456, 110, ['#7781'], BLUE),
    ('8888', 556, 460, 300, 110, ['no proximity', '??'], None),
]
CORRIDORS = [(244, 175, 300, 175), (500, 175, 556, 175), (144, 230, 144, 280), (400, 230, 400, 280),
             (706, 230, 706, 280), (244, 345, 300, 345), (500, 345, 556, 345), (144, 410, 144, 460),
             (706, 410, 706, 460)]


def y(h, m=0):
    """y position for a time given as hours after 11PM (h) plus minutes."""
    return TOP + PX_HOUR * (h + m / 60)


def build(left):
    out = []
    w = out.append
    w('<svg xmlns="http://www.w3.org/2000/svg" width="1920" height="1080" viewBox="0 0 1920 1080" '
      'font-family="Consolas, \'Courier New\', monospace">')
    w('<!-- Night Shift GUI mockup, 1920x1080. Based on docs/gui-mockup.webp. '
      'Generated by docs/gui-mockup.py: edit that rather than this file. -->')
    w('''<style>
    .panel { fill: #ffffff; stroke: #222222; stroke-width: 3; }
    .thin { fill: none; stroke: #222222; stroke-width: 2; }
    .grid15 { stroke: #ececec; stroke-width: 1; }
    .gridhr { stroke: #c8c8c8; stroke-width: 1; }
    .label { font-size: 22px; fill: #222222; }
    .small { font-size: 15px; fill: #222222; }
    .tiny { font-size: 12px; fill: #555555; }
    .muted { fill: #888888; }
    .button { fill: #f2f2f2; stroke: #222222; stroke-width: 2; }
    .button-on { fill: #222222; stroke: #222222; stroke-width: 2; }
    .room { fill: #fafafa; stroke: #222222; stroke-width: 2; }
</style>''')
    w('<rect width="1920" height="1080" fill="#e9e9e9"/>')

    def swap_button(x, text):
        w(f'<rect class="button-on" x="{x}" y="26" width="170" height="32"/>')
        w(f'<text class="small" x="{x + 12}" y="48" style="fill:#ffffff">{text}</text>')

    def click_hint(x, yy):
        w(f'<text class="tiny" x="{x}" y="{yy}">left click: viewer 1 · right click: viewer 2</text>')

    # ---------------- timeline helpers ----------------
    def hour_labels(x):
        labels = ['11PM', '12AM', '1AM', '2AM', '3AM', '4AM', '5AM', '6AM', '7AM']
        for i, t in enumerate(labels):
            w(f'<text class="tiny" x="{x}" y="{y(i) + 4}">{t}</text>')

    def column(x, wd, header, sub, colour, logs):
        if colour:
            w(f'<rect x="{x}" y="66" width="{wd}" height="6" fill="{colour}"/>')
        w(f'<text class="small" x="{x + 4}" y="90">{header}</text>')
        if sub:
            w(f'<text class="tiny" x="{x + 4}" y="104">{sub}</text>')
        w(f'<rect class="panel" x="{x}" y="{TOP}" width="{wd}" height="{BOTTOM - TOP}"/>')
        for q in range(1, 32):
            cls = 'gridhr' if q % 4 == 0 else 'grid15'
            yy = TOP + q * PX_HOUR / 4
            w(f'<line class="{cls}" x1="{x + 2}" y1="{yy}" x2="{x + wd - 2}" y2="{yy}"/>')
        for name, start, end, c, locked in logs:
            fill = '#fde3e3' if c == RED else '#e1eafc'
            dash = '' if locked else ' stroke-dasharray="6 4"'
            w(f'<rect x="{x + 5}" y="{y(*start)}" width="{wd - 10}" height="{y(*end) - y(*start)}" '
              f'fill="{fill}" stroke="{c}" stroke-width="3"{dash}/>')
            w(f'<text class="tiny" x="{x + 9}" y="{y(*start) + 16}" style="fill:{c}">{name}</text>')

    def time_marker(x1, x2):
        yt = y(2, 10)
        w(f'<line x1="{x1}" y1="{yt}" x2="{x2}" y2="{yt}" stroke="#f2a900" stroke-width="3"/>')
        w(f'<rect x="{x1 + 2}" y="{yt - 12}" width="40" height="24" fill="#f2a900"/>')
        w(f'<text class="tiny" x="{x1 + 5}" y="{yt + 4}" style="fill:#222222">01:10</text>')

    log1 = ('Log 1', (0, 45), (2, 30), RED, True)
    log3 = ('Log 3', (4, 30), (6, 0), RED, False)
    log2 = ('Log 2', (1, 15), (3, 0), BLUE, False)

    if left == 'map':
        # ---------------- map panel: facility map ----------------
        w(f'<rect class="panel" x="{LEFT_X}" y="16" width="{LEFT_W}" height="600"/>')
        w(f'<text class="label" x="{LEFT_X + 16}" y="50">MAP</text>')
        swap_button(LEFT_X + LEFT_W - 186, '⇄ ALL ROOMS')
        w(f'<text class="tiny" x="{LEFT_X + 16}" y="76">badge IDs in each room at 01:10</text>')
        for rid, rx, ry, rw, rh, ids, dot in ROOMS:
            name = rid + (' Entryway' if rid == '1111' else '')
            w(f'<rect class="room" x="{rx}" y="{ry}" width="{rw}" height="{rh}"/>')
            w(f'<text class="small" x="{rx + 10}" y="{ry + 22}">{name}</text>')
            for i, t in enumerate(ids):
                w(f'<text class="tiny" x="{rx + 10}" y="{ry + 46 + i * 18}">{t}</text>')
            if dot:
                w(f'<circle cx="{rx + rw - 14}" cy="{ry + 16}" r="7" fill="{dot}"/>')
        for x1, y1, x2, y2 in CORRIDORS:
            w(f'<line class="thin" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}"/>')
        # zoom controls; the map also scrolls (drag to pan)
        zx = LEFT_X + LEFT_W - 280
        for i, t in enumerate(['+', '−']):
            w(f'<rect class="button" x="{zx + i * 42}" y="25" width="34" height="34"/>')
            w(f'<text class="label" x="{zx + i * 42 + 10}" y="49">{t}</text>')
        w(f'<text class="tiny" x="{LEFT_X + 16}" y="586">dot = room shown in viewer 1 / 2 · drag to scroll · +/− to zoom</text>')
        click_hint(LEFT_X + 16, 604)

        # ---------------- map panel: tabs ----------------
        w(f'<rect class="panel" x="{LEFT_X}" y="632" width="{LEFT_W}" height="432"/>')
        w('<rect x="16" y="632" width="160" height="44" fill="#222222"/>')
        w('<text class="label" x="60" y="662" style="fill:#ffffff">Users</text>')
        w('<rect class="thin" x="176" y="632" width="160" height="44"/>')
        w('<text class="label" x="222" y="662">Rooms</text>')
        w('<rect class="thin" x="336" y="632" width="160" height="44"/>')
        w('<text class="label" x="370" y="662">Symbols</text>')
        w('<text class="small muted" x="32" y="708">BADGE ID</text>')
        w('<text class="small muted" x="220" y="708">NAME</text>')
        w('<text class="small muted" x="480" y="708">ROLE</text>')
        w(f'<line class="gridhr" x1="28" y1="718" x2="{LEFT_X + LEFT_W - 12}" y2="718"/>')
        for i, (bid, name, role) in enumerate([('#2210', None, None), ('#3302', None, None),
                                               ('#4553', 'Bob', 'Security'), ('#5120', None, None),
                                               ('#7781', None, None)]):
            yy = 746 + i * 32
            w(f'<text class="small" x="32" y="{yy}">{bid}</text>')
            w(f'<text class="small{"" if name else " muted"}" x="220" y="{yy}">{name or "________"}</text>')
            w(f'<text class="small{"" if role else " muted"}" x="480" y="{yy}">{role or "________"}</text>')
    else:
        # ---------------- room/timeline panel ----------------
        w(f'<rect class="panel" x="{LEFT_X}" y="16" width="{LEFT_W}" height="1048" style="fill:#f7f7f7"/>')
        w(f'<text class="label" x="{LEFT_X + 16}" y="50">ALL ROOMS</text>')
        swap_button(LEFT_X + LEFT_W - 186, '⇄ MAP')
        hour_labels(LEFT_X + 6)

        # unplaced column: new logs from a batch wait here, stacked in arrival order
        ux = LEFT_X + 44
        w(f'<text class="small" x="{ux + 2}" y="90">UNPLACED</text>')
        w(f'<rect class="panel" x="{ux}" y="{TOP}" width="74" height="{BOTTOM - TOP}" style="fill:#eeeeee"/>')
        by = TOP + 8
        for name, slots in [('Log 4', 4), ('Log 5', 2), ('Log 6', 6)]:
            w(f'<rect x="{ux + 5}" y="{by}" width="64" height="{slots * PX_HOUR / 4}" '
              f'fill="#f6f6f6" stroke="#666666" stroke-width="2" stroke-dasharray="6 4"/>')
            w(f'<text class="tiny" x="{ux + 9}" y="{by + 16}">{name}</text>')
            by += slots * PX_HOUR / 4 + 8
        w(f'<text class="tiny" x="{ux + 4}" y="{BOTTOM - 10}">new batch</text>')

        logs = {'1111': [log1, log3], '5555': [log2]}
        for i, (rid, *_rest, colour) in enumerate(sorted(ROOMS)):
            sub = 'Entry' if rid == '1111' else ''
            column(LEFT_X + 130 + i * 90, 82, rid, sub, colour, logs.get(rid, []))
        w(f'<text class="tiny" x="{LEFT_X + 6}" y="1046">grid = 15 min · solid = both locked · '
          f'dashed = not fully locked · room columns scroll sideways</text>')
        click_hint(LEFT_X + 6, 1058)
        time_marker(LEFT_X, LEFT_X + LEFT_W)

    # ---------------- viewer panels ----------------
    def viewer(x, num, colour, room, desc, log, status, status_colour, locks, lines):
        w(f'<rect class="panel" x="{x}" y="16" width="{V_W}" height="1048"/>')
        w(f'<rect x="{x}" y="16" width="{V_W}" height="8" fill="{colour}"/>')
        w(f'<text class="label" x="{x + 16}" y="56">VIEWER {num}</text>')
        w(f'<rect class="button" x="{x + 16}" y="70" width="180" height="40"/>')
        w(f'<text class="small" x="{x + 26}" y="88">Room {room}</text>')
        w(f'<text class="tiny" x="{x + 26}" y="104">({desc})</text>')
        w(f'<path d="M {x + 172} 86 L {x + 186} 86 L {x + 179} 98 Z" fill="#222222"/>')
        for i, (name, on) in enumerate(zip(['ROOM', 'TIME'], locks)):
            bx = x + 206 + i * 100
            w(f'<rect class="{"button-on" if on else "button"}" x="{bx}" y="70" width="92" height="40"/>')
            style = ' style="fill:#ffffff"' if on else ''
            w(f'<text class="tiny" x="{bx + 10}" y="87"{style}>LOCK</text>')
            w(f'<text class="tiny" x="{bx + 10}" y="102"{style}>{name}{" ✓" if on else ""}</text>')
        w(f'<text class="small" x="{x + 16}" y="138">SELECTED: {log} · '
          f'<tspan fill="{status_colour}">{status}</tspan></text>')
        w(f'<line class="thin" x1="{x}" y1="152" x2="{x + V_W}" y2="152"/>')
        for yy, t, text, hl in lines:
            if hl:
                w(f'<rect x="{x + 4}" y="{yy - 22}" width="{V_W - 8}" height="{hl}" fill="#fff3c4"/>')
            if t:
                w(f'<text class="small{"" if hl else " muted"}" x="{x + 12}" y="{yy}">{t}</text>')
            w(f'<text class="small" x="{x + 66}" y="{yy}">{text}</text>')
        w(f'<text class="tiny" x="{x + 16}" y="1052">current system time is always centred</text>')

    viewer(V1_X, 1, RED, '1111', 'Entryway', 'LOG #1', 'CORRECT', '#2e7d32', (True, True), [
        (480, '01:07', '&lt;ID#4553 - Bob&gt; Evening. Badge?', 0),
        (516, '01:08', '&lt;ID#2210&gt; Here. Night crew.', 0),
        (552, '01:09', '&lt;ID#4553 - Bob&gt; You\'re late.', 0),
        (604, '01:10', '[LOUD CRASH]', 62),
        (630, None, '&lt;ID#4553 - Bob&gt; What was that?', 0),
        (682, '01:11', '&lt;ID#2210&gt; Came from downstairs.', 0),
        (718, '01:12', '▒▒░▓ ...', 0),
    ])
    viewer(V2_X, 2, BLUE, '5555', 'unnamed', 'LOG #2', 'ROOM LOCKED', '#888888', (True, False), [
        (516, '01:08', '&lt;ID#7781&gt; Is the vault sealed?', 0),
        (552, '01:09', '&lt;ID#7781&gt; Hello?', 0),
        (604, '01:10', '[DISTANT THUD]', 36),
        (652, '01:11', '&lt;ID#7781&gt; Did you hear that?', 0),
    ])

    # ---------------- timeline panel (follows the rooms in viewer 1 and 2) ----------------
    w(f'<rect class="panel" x="{TL_X}" y="16" width="{TL_W}" height="1048" style="fill:#f7f7f7"/>')
    w(f'<text class="small" x="{TL_X + 12}" y="46">TIMELINE</text>')
    hour_labels(TL_X + 4)
    column(TL_X + 42, 52, '1111', None, RED, [log1, log3])
    column(TL_X + 98, 52, '5555', None, BLUE, [log2])
    w(f'<text class="tiny" x="{TL_X + 6}" y="1056">VIEWER 1 / 2</text>')
    time_marker(TL_X, TL_X + TL_W)

    w('</svg>')
    return '\n'.join(out) + '\n'


for name, left in (('gui-mockup-map.svg', 'map'), ('gui-mockup-rooms.svg', 'rooms')):
    io.open(DOCS + name, 'w', encoding='utf-8', newline='\n').write(build(left))
print('written')
